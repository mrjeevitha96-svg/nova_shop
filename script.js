function formatPrice(price) {

    return new Intl.NumberFormat(
        "en-IN",
        {
            style: "currency",
            currency: "INR",
            maximumFractionDigits: 0
        }
    ).format(price);

}


/* =========================================================
   IMAGE FALLBACK
   ========================================================= */

function setupImageFallback(img, productName) {

    img.addEventListener("error", function () {

        if (this.dataset.fallback === "true") {
            return;
        }

        this.dataset.fallback = "true";

        this.src =
            `https://placehold.co/700x850/f0eee9/222222?text=${encodeURIComponent(productName)}`;

    });

}


/* =========================================================
   RENDER PRODUCTS
   ========================================================= */

function renderProducts() {

    if (!productGrid) return;

    let filteredProducts = [...products];


    /* CATEGORY */

    if (currentCategory !== "All") {

        filteredProducts =
            filteredProducts.filter(
                product =>
                    product.category === currentCategory
            );

    }


    /* SEARCH */

    if (currentSearch.trim() !== "") {

        const searchTerm =
            currentSearch.toLowerCase().trim();

        filteredProducts =
            filteredProducts.filter(product =>

                product.name
                    .toLowerCase()
                    .includes(searchTerm)

                ||

                product.category
                    .toLowerCase()
                    .includes(searchTerm)

            );

    }


    /* SORT */

    if (currentSort === "low") {

        filteredProducts.sort(
            (a, b) => a.price - b.price
        );

    }

    if (currentSort === "high") {

        filteredProducts.sort(
            (a, b) => b.price - a.price
        );

    }

    if (currentSort === "az") {

        filteredProducts.sort(
            (a, b) =>
                a.name.localeCompare(b.name)
        );

    }

    if (currentSort === "za") {

        filteredProducts.sort(
            (a, b) =>
                b.name.localeCompare(a.name)
        );

    }


    /* NO RESULTS */

    if (filteredProducts.length === 0) {

        productGrid.innerHTML = `
            <div class="no-results">
                <h3>No products found</h3>
                <p>
                    Try another search or category.
                </p>
            </div>
        `;

        return;

    }


    /* PRODUCT CARDS */

    productGrid.innerHTML =
        filteredProducts.map(product => `

            <article
                class="product-card"
                data-product-id="${product.id}"
            >

                <div class="product-image">

                    ${
                        product.tag
                            ? `
                                <span class="product-tag">
                                    ${product.tag}
                                </span>
                              `
                            : ""
                    }

                    <img
                        src="${product.image}"
                        alt="${product.name}"
                        loading="lazy"
                    >

                    <button
                        class="quick-add"
                        data-add="${product.id}"
                        aria-label="Add ${product.name} to bag"
                    >
                        +
                    </button>

                </div>

                <div class="product-info">

                    <div class="product-category">
                        ${product.category}
                    </div>

                    <div class="product-name">
                        ${product.name}
                    </div>

                    <div class="product-price">
                        ${formatPrice(product.price)}
                    </div>

                </div>

            </article>

        `).join("");


    /* IMAGE FALLBACKS */

    productGrid
        .querySelectorAll("img")
        .forEach(img => {

            setupImageFallback(
                img,
                img.alt
            );

        });


    /* ADD BUTTONS */

    productGrid
        .querySelectorAll("[data-add]")
        .forEach(button => {

            button.addEventListener(
                "click",
                () => {

                    const id =
                        Number(button.dataset.add);

                    addToCart(id);

                }
            );

        });

}


